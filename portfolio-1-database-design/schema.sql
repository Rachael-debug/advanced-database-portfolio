CREATE TABLE faculty (
  faculty_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL
);

CREATE TABLE department (
  dept_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  faculty_id int NOT NULL
);

CREATE TABLE programme (
  programme_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  dept_id int NOT NULL,
  duration_years int
);

CREATE TABLE student (
  student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matric_no varchar(20) UNIQUE NOT NULL,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  email varchar(100) UNIQUE,
  programme_id int NOT NULL,
  entry_year int,
  current_level int
);

CREATE TABLE lecturer (
  lecturer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_no varchar(20) UNIQUE NOT NULL,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  email varchar(100) UNIQUE,
  academic_rank varchar(50),
  dept_id int NOT NULL
);

CREATE TABLE course (
  course_code varchar(10) PRIMARY KEY,
  title varchar(150) NOT NULL,
  credit_units int NOT NULL,
  level int NOT NULL,
  dept_id int NOT NULL
);

CREATE TABLE academic_session (
  session_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(20) UNIQUE NOT NULL,
  start_date date,
  end_date date
);

CREATE TABLE course_offering (
  offering_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_code varchar(10) NOT NULL,
  session_id int NOT NULL,
  semester int NOT NULL,
  lecturer_id int NOT NULL,
  capacity int NOT NULL
);

CREATE TABLE registration (
  registration_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id int NOT NULL,
  offering_id int NOT NULL,
  reg_date timestamp NOT NULL DEFAULT (now()),
  status varchar(20) NOT NULL DEFAULT 'registered'
);

CREATE TABLE result (
  result_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id int UNIQUE NOT NULL,
  ca_score int,
  exam_score int,
  status varchar(20) NOT NULL DEFAULT 'draft',
  entered_by int NOT NULL,
  entered_at timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE grade_scale (
  grade char(1) PRIMARY KEY,
  min_score int NOT NULL,
  max_score int NOT NULL,
  grade_point int NOT NULL
);

CREATE UNIQUE INDEX ON course_offering (course_code, session_id, semester);

CREATE UNIQUE INDEX ON registration (student_id, offering_id);

COMMENT ON COLUMN course.credit_units IS 'CHECK 1-6, added in SQL';

COMMENT ON COLUMN "course_offering"."semester" IS 'CHECK 1 or 2';

COMMENT ON COLUMN "course_offering"."capacity" IS 'CHECK > 0';

COMMENT ON COLUMN "registration"."status" IS 'CHECK registered, dropped';

COMMENT ON COLUMN "result"."ca_score" IS 'CHECK 0-40';

COMMENT ON COLUMN "result"."exam_score" IS 'CHECK 0-60';

COMMENT ON COLUMN "result"."status" IS 'CHECK draft, approved, published';

COMMENT ON TABLE "grade_scale" IS 'Lookup table. Matched to result by score range, not by foreign key';

COMMENT ON COLUMN "grade_scale"."min_score" IS 'CHECK 0-100';

COMMENT ON COLUMN "grade_scale"."max_score" IS 'CHECK 0-100, >= min_score';

COMMENT ON COLUMN "grade_scale"."grade_point" IS 'CHECK 0-5';

