DROP TABLE IF EXISTS result, registration, course_offering, academic_session, course, lecturer, student, programme, department, faculty, grade_scale CASCADE;

CREATE TABLE faculty (
  faculty_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL
);

CREATE TABLE department (
  dept_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  faculty_id int NOT NULL
);

CREATE TABLE programme (
  programme_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  dept_id int NOT NULL,
  duration_years int
);

CREATE TABLE student (
  student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matric_no varchar(20) UNIQUE NOT NULL,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  email varchar(100) UNIQUE,
  programme_id int NOT NULL,
  entry_year int,
  current_level int
);

CREATE TABLE lecturer (
  lecturer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_no varchar(20) UNIQUE NOT NULL,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  email varchar(100) UNIQUE,
  academic_rank varchar(50),
  dept_id int NOT NULL
);

CREATE TABLE course (
  course_code varchar(10) PRIMARY KEY,
  title varchar(150) NOT NULL,
  credit_units int NOT NULL,
  level int NOT NULL,
  dept_id int NOT NULL
);

CREATE TABLE academic_session (
  session_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(20) UNIQUE NOT NULL,
  start_date date,
  end_date date
);

CREATE TABLE course_offering (
  offering_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_code varchar(10) NOT NULL,
  session_id int NOT NULL,
  semester int NOT NULL,
  lecturer_id int NOT NULL,
  capacity int NOT NULL
);

CREATE TABLE registration (
  registration_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id int NOT NULL,
  offering_id int NOT NULL,
  reg_date timestamp NOT NULL DEFAULT (now()),
  status varchar(20) NOT NULL DEFAULT 'registered'
);

CREATE TABLE result (
  result_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id int UNIQUE NOT NULL,
  ca_score int,
  exam_score int,
  status varchar(20) NOT NULL DEFAULT 'draft',
  entered_by int NOT NULL,
  entered_at timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE grade_scale (
  grade char(1) PRIMARY KEY,
  min_score int NOT NULL,
  max_score int NOT NULL,
  grade_point int NOT NULL
);

CREATE UNIQUE INDEX ON course_offering (course_code, session_id, semester);

CREATE UNIQUE INDEX ON registration (student_id, offering_id);


-- ON DELETE RESTRICT: academic records must never be deleted by accident
ALTER TABLE department ADD FOREIGN KEY (faculty_id) REFERENCES faculty (faculty_id) ON DELETE RESTRICT;
ALTER TABLE programme ADD FOREIGN KEY (dept_id) REFERENCES department (dept_id) ON DELETE RESTRICT;
ALTER TABLE student ADD FOREIGN KEY (programme_id) REFERENCES programme (programme_id) ON DELETE RESTRICT;
ALTER TABLE lecturer ADD FOREIGN KEY (dept_id) REFERENCES department (dept_id) ON DELETE RESTRICT;
ALTER TABLE course ADD FOREIGN KEY (dept_id) REFERENCES department (dept_id) ON DELETE RESTRICT;

-- course_code is a natural key, so a renamed code will update automatically in course_offering
ALTER TABLE course_offering ADD FOREIGN KEY (course_code) REFERENCES course (course_code) ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE course_offering ADD FOREIGN KEY (session_id) REFERENCES academic_session (session_id) ON DELETE RESTRICT;
ALTER TABLE course_offering ADD FOREIGN KEY (lecturer_id) REFERENCES lecturer (lecturer_id) ON DELETE RESTRICT;
ALTER TABLE registration ADD FOREIGN KEY (student_id) REFERENCES student (student_id) ON DELETE RESTRICT;
ALTER TABLE registration ADD FOREIGN KEY (offering_id) REFERENCES course_offering (offering_id) ON DELETE RESTRICT;
ALTER TABLE result ADD FOREIGN KEY (registration_id) REFERENCES registration (registration_id) ON DELETE RESTRICT;
ALTER TABLE result ADD FOREIGN KEY (entered_by) REFERENCES lecturer (lecturer_id) ON DELETE RESTRICT;

-- For checking constraints

ALTER TABLE course
  ADD CONSTRAINT chk_credit_units CHECK (credit_units BETWEEN 1 AND 6);

ALTER TABLE course_offering
  ADD CONSTRAINT chk_semester CHECK (semester IN (1, 2)),
  ADD CONSTRAINT chk_capacity CHECK (capacity > 0);

ALTER TABLE registration
  ADD CONSTRAINT chk_reg_status CHECK (status IN ('registered', 'dropped'));

ALTER TABLE result
  ADD CONSTRAINT chk_ca_score CHECK (ca_score BETWEEN 0 AND 40),
  ADD CONSTRAINT chk_exam_score CHECK (exam_score BETWEEN 0 AND 60),
  ADD CONSTRAINT chk_result_status CHECK (status IN ('draft', 'approved', 'published'));

ALTER TABLE academic_session
  ADD CONSTRAINT chk_session_dates CHECK (end_date > start_date);

ALTER TABLE grade_scale
  ADD CONSTRAINT chk_min_score CHECK (min_score BETWEEN 0 AND 100),
  ADD CONSTRAINT chk_max_score CHECK (max_score BETWEEN 0 AND 100),
  ADD CONSTRAINT chk_score_range CHECK (min_score <= max_score),
  ADD CONSTRAINT chk_grade_point CHECK (grade_point BETWEEN 0 AND 5);

